export const HEXAGRAMS: HexagramData[] = HEXAGRAM_ROWS.map(([number, name, , judgment, image, keywordText, advice], index) => {
  const pattern = KING_WEN_PATTERNS[index];
  const lower = TRIGRAMS[pattern.slice(0, 3) as TrigramKey];
  const upper = TRIGRAMS[pattern.slice(3, 6) as TrigramKey];
  return {
    number,
    name,
    reading: NAME_READING_OVERRIDES[number] ?? name,
    unicode: String.fromCodePoint(0x4dc0 + number - 1),
    judgment,
    image,
    keywords: keywordText.split("・"),
    advice,
    lineAdvice: number === 1 ? DEFAULT_LINES : DEFAULT_LINES.map((line, i) => `${upper.name}（${upper.nature}）と${lower.name}（${lower.nature}）の象を踏まえ、${i + 1}番目の段階では${advice}`),
  };
});

export function getHexagram(lines: boolean[]): HexagramData {
  if (lines.length !== 6) throw new Error("卦は下から上へ6本の爻が必要です。");
  const pattern = lines.map((yang) => yang ? "1" : "0").join("");
  const index = KING_WEN_PATTERNS.indexOf(pattern as TrigramKey);
  if (index < 0) throw new Error("卦を特定できませんでした。");
  return HEXAGRAMS[index];
}

export function getLinesForHexagram(number: number): boolean[] {
  if (!Number.isInteger(number) || number < 1 || number > 64) throw new Error("卦番号は1から64で指定してください。");
  return KING_WEN_PATTERNS[number - 1].split("").map((line) => line === "1");
}

export function getTrigrams(lines: boolean[]) {
  if (lines.length !== 6) throw new Error("卦は下から上へ6本の爻が必要です。");
  return {
    lower: TRIGRAMS[lines.slice(0, 3).map((yang) => yang ? "1" : "0").join("") as TrigramKey],
    upper: TRIGRAMS[lines.slice(3, 6).map((yang) => yang ? "1" : "0").join("") as TrigramKey],
  };
}
